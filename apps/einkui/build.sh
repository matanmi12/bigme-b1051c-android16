#!/bin/bash
# Gradle-free build of the SystemUI overlay plugin. The plugin interfaces are compile-only stubs (SystemUI provides
# the real ones at runtime); the APK is signed with the public AOSP test platform key, which this GSI's SystemUI uses,
# so it gets com.android.systemui.permission.PLUGIN. Output: build/einkui.apk
set -euo pipefail
cd "$(dirname "$0")"
SDK=/opt/homebrew/share/android-commandlinetools
BT=$SDK/build-tools/36.0.0
AJ=$SDK/platforms/android-35/android.jar
KEYS=../../sysui/keys
export JAVA_HOME=/opt/homebrew/opt/openjdk@17
export PATH="$JAVA_HOME/bin:$PATH"
# No defaults: the highest build wins at runtime (EinkOverlayPlugin), so a forgotten VERSION_CODE (old default 1)
# would ship a plugin that stays idle.
: "${VERSION_CODE:?set VERSION_CODE (higher than the installed build)}" "${VERSION_NAME:?set VERSION_NAME}"
rm -rf build && mkdir -p build/gen/org/b1051c/einkui build/stubs build/classes build/dex
printf 'package org.b1051c.einkui;\n\n/** Generated by build.sh. */\nfinal class Build {\n    static final int CODE = %d;\n    static final String NAME = "%s";\n    private Build() {}\n}\n' \
  "$VERSION_CODE" "$VERSION_NAME" > build/gen/org/b1051c/einkui/Build.java
"$BT/aapt2" compile --dir res -o build/res.zip
ASSETS=(); [ -d assets ] && ASSETS=(-A assets)   # fonts for the lock screen (Lilita One, Rubik Medium)
"$BT/aapt2" link -o build/base.apk -I "$AJ" --manifest AndroidManifest.xml --java build/gen build/res.zip "${ASSETS[@]}" \
  --min-sdk-version 31 --target-sdk-version 35 --version-code "$VERSION_CODE" --version-name "$VERSION_NAME"
javac -Xlint:-options -source 17 -target 17 -encoding UTF-8 -classpath "$AJ" -d build/stubs $(find stubs -name '*.java')
javac -Xlint:-options -source 17 -target 17 -encoding UTF-8 -classpath "$AJ:build/stubs" -d build/classes \
  $(find src build/gen -name '*.java')
"$BT/d8" --lib "$AJ" --classpath build/stubs --min-api 31 --release --output build/dex $(find build/classes -name '*.class')
cp build/base.apk build/unsigned.apk
(cd build/dex && zip -q ../unsigned.apk classes.dex)
"$BT/zipalign" -f -p 4 build/unsigned.apk build/aligned.apk
"$BT/apksigner" sign --key "$KEYS/platform.pk8" --cert "$KEYS/platform.x509.pem" --out build/einkui.apk build/aligned.apk
"$BT/apksigner" verify --print-certs build/einkui.apk | grep -m1 "SHA-256" && shasum -a 256 build/einkui.apk
